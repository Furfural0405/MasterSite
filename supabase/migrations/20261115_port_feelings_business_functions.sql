-- Originally public.check_registration_rate_limit (p_email text, p_ip text)
CREATE OR REPLACE FUNCTION mastersite_feelings.check_registration_rate_limit(p_email text, p_ip text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_email_hash text;
  v_ip_hash text;
  v_email_attempts integer;
  v_ip_attempts integer;
begin
  v_email_hash := encode(extensions.digest(lower(trim(coalesce(p_email, ''))), 'sha256'), 'hex');
  v_ip_hash := encode(extensions.digest(coalesce(nullif(trim(p_ip), ''), 'unknown'), 'sha256'), 'hex');

  delete from mastersite_feelings_private.registration_rate_limits
  where attempted_at < now() - interval '24 hours';

  select count(*) into v_email_attempts
  from mastersite_feelings_private.registration_rate_limits
  where email_hash = v_email_hash
    and attempted_at >= now() - interval '60 minutes';

  select count(*) into v_ip_attempts
  from mastersite_feelings_private.registration_rate_limits
  where ip_hash = v_ip_hash
    and attempted_at >= now() - interval '15 minutes';

  if v_email_attempts >= 3 or v_ip_attempts >= 8 then
    return false;
  end if;

  insert into mastersite_feelings_private.registration_rate_limits (email_hash, ip_hash)
  values (v_email_hash, v_ip_hash);

  return true;
end;
$function$;

