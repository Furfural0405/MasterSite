-- Originally public.get_public_tournament_snapshot ()
CREATE OR REPLACE FUNCTION mastersite_feelings.get_public_tournament_snapshot()
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  with source as (
    select
      s.competition,
      s.scoring,
      t.payload,
      case
        when jsonb_typeof(t.payload->'groups') = 'array'
        then jsonb_array_length(t.payload->'groups')
        else 0
      end as group_count
    from mastersite_feelings.site_settings s
    cross join mastersite_feelings.tournament_state t
    where s.id = 1 and t.id = 1
  ),
  grouped_ids as (
    select distinct ids.participant_id::uuid as participant_id
    from source src
    cross join lateral jsonb_array_elements(
      case when src.group_count > 0 then src.payload->'groups' else '[]'::jsonb end
    ) as grp(value)
    cross join lateral jsonb_array_elements_text(grp.value->'participantIds') as ids(participant_id)
  ),
  public_participants as (
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', p.id,
          'name', p.name,
          'team_size', p.team_size,
          'members', '[]'::jsonb
        )
        order by p.created_at, p.id
      ),
      '[]'::jsonb
    ) as participants
    from mastersite_feelings.participants p
    join grouped_ids g on g.participant_id = p.id
  )
  select jsonb_build_object(
    'competition', src.competition,
    'scoring', src.scoring,
    'participants', case when src.group_count > 0 then pp.participants else '[]'::jsonb end,
    'state', case when src.group_count > 0 then src.payload else null end
  )
  from source src
  cross join public_participants pp;
$function$;

-- Originally public.register_tournament_entry (p_name text, p_members jsonb)
CREATE OR REPLACE FUNCTION mastersite_feelings.register_tournament_entry(p_name text, p_members jsonb)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_name text := trim(coalesce(p_name, ''));
  v_team_size integer := mastersite_feelings.current_tournament_team_size();
  v_members jsonb := coalesce(p_members, '[]'::jsonb);
  v_member text;
  v_id uuid;
begin
  if not mastersite_feelings.current_tournament_registration_open() then
    raise exception 'Die Turnier-Anmeldung ist aktuell geschlossen.';
  end if;

  if char_length(v_name) not between 2 and 40 then
    raise exception 'Name oder Teamname muss zwischen 2 und 40 Zeichen lang sein.';
  end if;

  if jsonb_typeof(v_members) <> 'array' then
    raise exception 'Ungültige Teammitglieder.';
  end if;

  if jsonb_array_length(v_members) <> v_team_size then
    raise exception 'Der aktive Turniermodus ist %vs%. Erwartet werden genau % Spieler.',
      v_team_size, v_team_size, v_team_size;
  end if;

  for v_member in select value from jsonb_array_elements_text(v_members)
  loop
    if char_length(trim(v_member)) not between 2 and 40 then
      raise exception 'Jeder Name oder Gamer-Tag muss zwischen 2 und 40 Zeichen lang sein.';
    end if;
  end loop;

  insert into mastersite_feelings.participants (name, submitted_by, team_size, members)
  values (
    v_name,
    auth.uid(),
    v_team_size,
    (
      select jsonb_agg(trim(value))
      from jsonb_array_elements_text(v_members)
    )
  )
  returning id into v_id;

  return v_id;
end;
$function$;

-- Originally public.restore_tournament_backup (p_participants jsonb, p_state jsonb, p_competition jsonb, p_scoring jsonb)
CREATE OR REPLACE FUNCTION mastersite_feelings.restore_tournament_backup(p_participants jsonb, p_state jsonb, p_competition jsonb, p_scoring jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  participant jsonb;
  restore_team_size integer;
  participant_team_size integer;
  participant_members jsonb;
  participant_name text;
  restored_competition jsonb;
  backup_has_groups boolean;
begin
  if not mastersite_feelings_private.is_approved_admin() then
    raise exception 'Nur freigeschaltete Admins dürfen Turnier-Backups wiederherstellen.';
  end if;

  if jsonb_typeof(p_participants) <> 'array'
     or jsonb_typeof(p_state) <> 'object'
     or jsonb_typeof(p_competition) <> 'object'
     or jsonb_typeof(p_scoring) <> 'object' then
    raise exception 'Ungültiges Turnier-Backup.';
  end if;

  restore_team_size := greatest(
    1,
    least(5, coalesce(nullif(p_competition->>'teamSize', '')::integer, 1))
  );

  backup_has_groups :=
    jsonb_typeof(p_state->'groups') = 'array'
    and jsonb_array_length(p_state->'groups') > 0;

  restored_competition :=
    coalesce(p_competition, '{}'::jsonb)
    || jsonb_build_object(
      'registrationEnabled',
      case
        when backup_has_groups then false
        else coalesce((p_competition->>'registrationEnabled')::boolean, true)
      end
    );

  for participant in select value from jsonb_array_elements(p_participants)
  loop
    participant_name := trim(coalesce(participant->>'name', ''));
    participant_team_size := greatest(
      1,
      least(
        5,
        coalesce(
          nullif(participant->>'teamSize', '')::integer,
          nullif(participant->>'team_size', '')::integer,
          1
        )
      )
    );
    participant_members := coalesce(participant->'members', '[]'::jsonb);

    if participant_name = '' or char_length(participant_name) not between 2 and 40 then
      raise exception 'Ungültiger Teilnehmer-/Teamname im Backup.';
    end if;

    if participant_team_size <> restore_team_size then
      raise exception 'Backup enthält Teilnehmer/Teams mit einer anderen Teamgröße als der gespeicherte Turniermodus.';
    end if;

    if jsonb_typeof(participant_members) <> 'array'
       or jsonb_array_length(participant_members) <> participant_team_size then
      raise exception 'Ungültige Mitgliederliste für %.', participant_name;
    end if;

    if exists (
      select 1
      from jsonb_array_elements_text(participant_members) as member(value)
      where char_length(trim(member.value)) not between 2 and 40
    ) then
      raise exception 'Ungültiger Spielername im Team %.', participant_name;
    end if;
  end loop;

  update mastersite_feelings.site_settings
  set competition = restored_competition,
      scoring = p_scoring,
      updated_at = now(),
      updated_by = auth.uid()
  where id = 1;

  delete from mastersite_feelings.participants;

  for participant in select value from jsonb_array_elements(p_participants)
  loop
    insert into mastersite_feelings.participants (id, name, team_size, members, submitted_by)
    values (
      (participant->>'id')::uuid,
      trim(participant->>'name'),
      greatest(
        1,
        least(
          5,
          coalesce(
            nullif(participant->>'teamSize', '')::integer,
            nullif(participant->>'team_size', '')::integer,
            1
          )
        )
      ),
      participant->'members',
      null
    );
  end loop;

  insert into mastersite_feelings.tournament_state (id, payload, updated_at, updated_by)
  values (1, p_state, now(), auth.uid())
  on conflict (id) do update
  set payload = excluded.payload,
      updated_at = excluded.updated_at,
      updated_by = excluded.updated_by;
end;
$function$;

-- Originally public.set_tournament_registration_enabled (p_enabled boolean)
CREATE OR REPLACE FUNCTION mastersite_feelings.set_tournament_registration_enabled(p_enabled boolean)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  groups_started boolean;
begin
  if not mastersite_feelings_private.is_approved_admin() then
    raise exception 'Nur freigeschaltete Admins dürfen die Turnier-Anmeldung ändern.';
  end if;

  select
    jsonb_typeof(t.payload->'groups') = 'array'
    and jsonb_array_length(t.payload->'groups') > 0
  into groups_started
  from mastersite_feelings.tournament_state t
  where t.id = 1;

  if p_enabled and coalesce(groups_started, false) then
    raise exception 'Die Anmeldung kann nicht geöffnet werden, solange eine Gruppenphase existiert.';
  end if;

  update mastersite_feelings.site_settings
  set competition = jsonb_set(
        coalesce(competition, '{}'::jsonb),
        '{registrationEnabled}',
        to_jsonb(p_enabled),
        true
      ),
      updated_at = now(),
      updated_by = auth.uid()
  where id = 1;

  return p_enabled;
end;
$function$;

